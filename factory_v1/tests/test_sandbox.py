    def git_boundary(self, argv, **kwargs):
        self.calls.append((argv, kwargs))
        args = argv[2:]
        reader = Path(argv[1].split('=', 1)[1])
        if args[0] == 'init':
            (reader / 'objects').mkdir()
            raw = b''
        elif args[0] == 'rev-parse':
            self.assertEqual(sorted(path.name for path in (reader / 'objects/pack').iterdir()),
                             ['pack-' + 'a' * 40 + '.idx', 'pack-' + 'a' * 40 + '.pack'])
            self.assertFalse((reader / 'config').exists())
            self.assertFalse((reader / 'objects/info/alternates').exists())
            raw = self.revision.encode() + b'\n'
        elif args[0] == 'ls-tree':
            raw = self.entry
        elif args[1] == '-s':
            raw = str(len(self.content)).encode()
        else:
            raw = self.content
        return subprocess.CompletedProcess(argv, 0, raw, b'')

    def snapshot(self):
        with patch.object(sandbox_source.subprocess, 'run', side_effect=self.git_boundary):
            return sandbox_source.snapshot(self.source, {'baseline': self.revision}, self.destination)

