class SourceSnapshotTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR'))
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root / 'source'
        self.source.mkdir()
        objects = self.source / '.git/objects'
        (objects / 'pack').mkdir(parents=True)
        (objects / 'pack' / ('pack-' + 'a' * 40 + '.pack')).write_bytes(b'labeled packed objects')
        (objects / 'pack' / ('pack-' + 'a' * 40 + '.idx')).write_bytes(b'labeled index')
        (objects / 'info').mkdir()
        (objects / 'info/alternates').write_text('/never-read')
        (self.source / '.git/config').write_text('[core]\nfsmonitor = touch /never-execute\n')
        (self.source / '.env').write_text('UNTRACKED_SECRET_FIXTURE=not-real\n')
        self.destination = self.root / 'copy'
        self.destination.mkdir()
        self.revision = 'b' * 40
        self.entry = b'100644 blob ' + b'c' * 40 + b'\thello.py\0'
        self.content = b'print("baseline")\n'
        self.calls = []

    def git_boundary(self, argv, **kwargs):
        self.calls.append((argv, kwargs))
        args = argv[2:]
        reader = Path(argv[1].split('=', 1)[1])
        if args[0] == 'init':
            (reader / 'objects').mkdir()
            raw = b''
        elif args[0] == 'rev-parse':
            self.assertEqual(sorted(path.name for path in (reader / 'objects/pack').iterdir()),
                             ['pack-' + 'a' * 40 + '.idx', 'pack-' + 'a' * 40 + '.pack'])
            self.assertFalse((reader / 'config').exists())
            self.assertFalse((reader / 'objects/info/alternates').exists())
            raw = self.revision.encode() + b'\n'
        elif args[0] == 'ls-tree':
            raw = self.entry
        elif args[1] == '-s':
            raw = str(len(self.content)).encode()
        else:
            raw = self.content
        return subprocess.CompletedProcess(argv, 0, raw, b'')

    def snapshot(self):
        with patch.object(sandbox_source.subprocess, 'run', side_effect=self.git_boundary):
            return sandbox_source.snapshot(self.source, {'baseline': self.revision}, self.destination)

    def test_packed_source_ignores_configuration_and_untracked_secrets(self):
        manifests = self.snapshot()
        self.assertEqual(manifests['baseline'], {'hello.py': {'sha256': hashlib.sha256(self.content).hexdigest(),
                                                             'bytes': len(self.content), 'executable': False}})
