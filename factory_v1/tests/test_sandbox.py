def write_worker_evidence(root, assignment, inputs=()):
    """Worker-output boundary fixture; no worker executes these declarations."""
    scratch = root / 'scratch'
    scratch.mkdir(exist_ok=True)
    (root / 'model-evidence').mkdir(exist_ok=True)
    (root / 'model-evidence/response-1.json').write_text('{"label":"mock response, not inference"}')
    loads = [{'source': item['source'], 'sha256': item['sha256'], 'tool_reference': 'read-' + str(index)}
             for index, item in enumerate(inputs)]
    events = [{'reference': load['tool_reference'], 'tool': 'read_file', 'args': {'path': item['path']},
               'result': json.dumps({'content': '1|' + (root / 'inputs' / Path(item['path']).name).read_text().rstrip('\n')})}
              for load, item in zip(loads, inputs)]
    test_command = 'python -m unittest labeled_component_fixture'
    output = 'LABELED OUTPUT, NOT NATIVE EXECUTION; exit 0'
    result = {'assignment_id': assignment['assignment_id'], 'handoff_digest': assignment['handoff_digest'],
              'claim_id': assignment['claim_id'], 'run_id': assignment['runtime']['run_id'], 'status': 'done',
              'loads': loads, 'work': ['labeled work declaration'],
              'artifacts': [{'name': 'stage-evidence', 'sha256': hashlib.sha256(b'labeled evidence').hexdigest(), 'content': 'labeled evidence'}],
              'tests': [{'command': test_command, 'result': output}]}
    conversation = {'messages': [
        {'role': 'assistant', 'tool_calls': [{'id': 'test', 'function': {'name': 'terminal',
         'arguments': json.dumps({'command': test_command})}}]},
        {'role': 'tool', 'tool_call_id': 'test', 'content': output}]}
    for name, value in [('result.json', result), ('loads.json', loads), ('conversation.json', conversation), ('probes.json', {})]:
        (scratch / name).write_text(json.dumps(value))
    (scratch / 'events.jsonl').write_text(''.join(json.dumps(event) + '\n' for event in events))
    return result


